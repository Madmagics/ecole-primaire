[titre]Additionner, c'est quoi ?[/titre]
Additionner, c'est [b]mettre ensemble[/b] pour savoir combien on a [b]en tout[/b].
Léo a 3 billes. Sa sœur lui en donne 2. Combien Léo a-t-il de billes maintenant ?
